impl Locale {
    pub fn from_code(code: &str) -> Self {
        match code {
            "en-US" => Self::EnUs,
            _ => Self::PtBr,
        }
    }

    pub fn code(self) -> &'static str {
        match self {
            Self::PtBr => "pt-BR",
            Self::EnUs => "en-US",
        }
    }
}

